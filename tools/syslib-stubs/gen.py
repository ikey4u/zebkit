#!/usr/bin/env python3
"""Generate lazy-loading stubs for an optional system library.

    gen.py SONAME LIBRARY.so OUT.S [--negative REGEX] [--string REGEX] [--default zero|negative]

For every function LIBRARY.so exports, OUT.S defines a function of the same
name that jumps through a pointer. The first call loads SONAME with dlopen,
looks the function up and patches the pointer; later calls are one indirect
jump. Linking the stubs instead of the library means the engine does not list
the library as a dependency: it starts without it, and uses it when present.

If the library or the function is missing, the call returns a "this failed"
value instead of crashing: 0/NULL by default, -1 for names matching
--negative, and an empty string for names matching --string. Callers already
treat those as failure (wl_display_connect() returning NULL, snd_pcm_open()
returning a negative error), so the feature that needs the library is simply
unavailable.

A stub works for any signature, variadic ones included, because it forwards
the call with every argument register untouched. Data symbols cannot be
forwarded this way and are not generated.

The resolver, zeb_syslib_resolve(), is in loader.c and is linked once.
"""

import argparse
import re
import subprocess


def exported_functions(library):
    out = subprocess.run(["nm", "-D", "--defined-only", library], check=True, capture_output=True, text=True).stdout
    names = set()
    for line in out.splitlines():
        parts = line.split()
        if len(parts) >= 3 and parts[1] in "TWi":
            names.add(parts[2].split("@")[0])
    return sorted(n for n in names if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", n))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("soname")
    parser.add_argument("library")
    parser.add_argument("output")
    parser.add_argument("--default", choices=["zero", "negative"], default="zero")
    parser.add_argument("--negative", default=None)
    parser.add_argument("--zero", default=None)
    parser.add_argument("--string", default=None)
    args = parser.parse_args()

    tag = re.sub(r"[^A-Za-z0-9]", "_", args.soname)
    lines = [
        f"/* Generated by tools/syslib-stubs/gen.py for {args.soname}. Do not edit. */",
        "    .text",
        f'    .section .rodata.zebstub.{tag},"a",@progbits',
        f"zebstub_soname_{tag}:",
        f'    .asciz "{args.soname}"',
        "",
        # One shared slow path per library. On entry r10 = symbol name,
        # r11 = address of the stub's pointer. Every register that can carry
        # an argument is saved around the call into the resolver.
        f'    .section .text.zebstub.{tag},"ax",@progbits',
        f"zebstub_lazy_{tag}:",
        "    pushq %rdi", "    pushq %rsi", "    pushq %rdx", "    pushq %rcx",
        "    pushq %r8", "    pushq %r9", "    pushq %rax", "    pushq %r11",
        "    subq $128, %rsp",
    ]
    lines += [f"    movdqu %xmm{i}, {16 * i}(%rsp)" for i in range(8)]
    lines += [
        f"    leaq zebstub_soname_{tag}(%rip), %rdi",
        "    movq %r10, %rsi",
        "    movq %r11, %rdx",
        "    movl %ebx, %ecx",
        "    callq zeb_syslib_resolve@PLT",
    ]
    lines += [f"    movdqu {16 * i}(%rsp), %xmm{i}" for i in range(8)]
    lines += [
        "    addq $128, %rsp",
        "    popq %r11", "    popq %rax", "    popq %r9", "    popq %r8",
        "    popq %rcx", "    popq %rdx", "    popq %rsi", "    popq %rdi",
        "    popq %rbx",
        "    jmpq *(%r11)",
        "",
    ]

    kinds = {"zero": 0, "negative": 1, "string": 2}
    for name in exported_functions(args.library):
        kind = args.default
        if args.negative and re.search(args.negative, name):
            kind = "negative"
        if args.zero and re.search(args.zero, name):
            kind = "zero"
        if args.string and re.search(args.string, name):
            kind = "string"
        lines += [
            f'    .section .text.zebstub.{name},"ax",@progbits',
            f"    .globl {name}",
            f"    .hidden {name}",
            f"    .type {name},@function",
            f"{name}:",
            f"    jmpq *zebstub_ptr_{name}(%rip)",
            # First call: pass the name, the pointer and the failure kind
            # (in ebx, which is saved here and restored by the slow path).
            f"zebstub_first_{name}:",
            "    pushq %rbx",
            f"    movl ${kinds[kind]}, %ebx",
            f"    leaq zebstub_name_{name}(%rip), %r10",
            f"    leaq zebstub_ptr_{name}(%rip), %r11",
            f"    jmp zebstub_lazy_{tag}",
            f'    .section .rodata.zebstub.{name},"a",@progbits',
            f"zebstub_name_{name}:",
            f'    .asciz "{name}"',
            f'    .section .data.zebstub.{name},"aw",@progbits',
            "    .p2align 3",
            f"zebstub_ptr_{name}:",
            f"    .quad zebstub_first_{name}",
            "",
        ]
    lines.append('    .section .note.GNU-stack,"",@progbits')
    with open(args.output, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
