#!/usr/bin/env python3
"""pdf_viewer.js as a C++ array, as automation_scripts.py makes its scripts.

    pdf_viewer_script.py <pdf_viewer.js> <out.h>
"""
import sys


def main():
    with open(sys.argv[1], encoding="utf-8") as f:
        source = f.read().encode("utf-8")
    with open(sys.argv[2], "w", encoding="utf-8") as out:
        out.write("// Generated by pdf_viewer_script.py.\n#pragma once\nnamespace zebkit {\n")
        out.write("inline constexpr char kPdfViewerScript[] = {\n")
        for i in range(0, len(source), 32):
            out.write(",".join(str(b if b < 128 else b - 256) for b in source[i:i + 32]) + ",\n")
        out.write("0};\n}  // namespace zebkit\n")


main()
