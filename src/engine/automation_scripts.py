#!/usr/bin/env python3
"""The script automation_renderer.cc runs in each world it automates, as a C++
array: a function of isUtilityWorld and isUnderTest whose value is the runner of
automation_steps.js, over Playwright's injected script
(playwright/injected_script.js) made with the InjectedScript's options. An
array rather than a string literal, which MSVC limits to 64 KiB.

And Playwright's clock (playwright/clock_script.js), installed as
server/clock.ts installs it, as kClockScript.

And the WebSocket mock (playwright/websocket_mock_script.js), installed as
webSocketRouteDispatcher.ts installs it, as kWebSocketMockScript.

And the WebMCP, coverage and WebAuthn scripts (playwright/webmcp_script.js,
playwright/coverage_script.js, playwright/webauthn_script.js) as kWebMcpScript,
kCoverageScript and kWebAuthnScript.

    automation_scripts.py <injected_script.js> <automation_steps.js> <clock_script.js> <websocket_mock_script.js>
        <snapshotter_script.js> <storage_script.js> <webmcp_script.js> <coverage_script.js>
        <webauthn_script.js> <out.h>
"""

import json
import sys

# InjectedScript's options, as Playwright's server gives them for Chromium
# (dom.ts's injectedScript(), crPage.ts's rafCountForStablePosition(),
# crExecutionContext.ts's shouldPrependErrorPrefix()).
OPTIONS = {
    "isUnderTest": False,
    "sdkLanguage": "javascript",
    "frameSeq": 0,
    "testIdAttributeName": "data-testid",
    "stableRafCount": 1,
    "browserName": "chromium",
    "shouldPrependErrorPrefix": False,
    "customEngines": [],
}


def main():
    (injected_path, steps_path, clock_path, mock_path, snapshotter_path, storage_path, webmcp_path,
     coverage_path, webauthn_path, out_path) = sys.argv[1:11]
    with open(webmcp_path, encoding="utf-8") as f:
        webmcp = f.read()
    with open(coverage_path, encoding="utf-8") as f:
        coverage = f.read()
    with open(webauthn_path, encoding="utf-8") as f:
        webauthn = f.read()
    with open(snapshotter_path, encoding="utf-8") as f:
        snapshotter = f.read()
    with open(storage_path, encoding="utf-8") as f:
        storage = f.read()
    with open(mock_path, encoding="utf-8") as f:
        mock = f.read()
    with open(clock_path, encoding="utf-8") as f:
        clock = f.read()
    with open(injected_path, encoding="utf-8") as f:
        injected = f.read()
    with open(steps_path, encoding="utf-8") as f:
        steps = f.read()
    # The steps in a scope of their own: the bundle's names are not theirs.
    source = ("((isUtilityWorld, isUnderTest) => {\nconst module = {};\nconst options = %s;\n%s\n;\n"
              "return (() => {\n%s\n})();\n})\n"
              % (json.dumps(OPTIONS), injected, steps))
    clock_source = ("(() => {\nconst module = {};\n%s\n;\nif (!globalThis.__pwClock)\n"
                    "  globalThis.__pwClock = (module.exports.inject())(globalThis, 'chromium');\n})();\n"
                    % clock)

    def array(name, text):
        data = text.encode("utf-8")
        lines = []
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 24]) + ",")
        return "inline constexpr unsigned char %s[] = {\n%s\n};\n" % (name, "\n".join(lines))
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("// Generated by automation_scripts.py from playwright/injected_script.js\n"
                "// and automation_steps.js. Do not edit.\n\n"
                "#ifndef ZEBKIT_ENGINE_AUTOMATION_SCRIPTS_H_\n"
                "#define ZEBKIT_ENGINE_AUTOMATION_SCRIPTS_H_\n\n"
                "#include <stddef.h>\n\n"
                "namespace zebkit {\n\n"
                "// UTF-8, without a terminating NUL.\n")
        f.write(array("kAutomationScript", source))
        f.write("\n// Playwright's clock, made in a document unless it has one.\n")
        f.write(array("kClockScript", clock_source))
        f.write("\n// Playwright's WebSocket mock, made in a document.\n")
        f.write(array("kWebSocketMockScript",
                      "(() => {\nconst module = {};\n%s\n;\n(module.exports.inject())(globalThis);\n})();\n" % mock))
        f.write("\n// Playwright's DOM snapshot streamer for traces: an expression whose value\n"
                "// is frameSnapshotStreamer(streamerName, removeNoScript).\n")
        f.write(array("kSnapshotterScript",
                      "(() => {\n%s\n;\nreturn frameSnapshotStreamer;\n})()" % snapshotter))
        f.write("\n// Playwright's storage script: an expression whose value is its class,\n"
                "// constructed with the browser's name (browserContext.ts's storageState()).\n")
        f.write(array("kStorageScript",
                      "(() => {\nconst module = {};\n%s\n;\nreturn module.exports.StorageScript();\n})()" % storage))
        f.write("\n// Playwright's WebMCP script: an expression whose value is its class,\n"
                "// constructed with the frame's global (server/webmcp.ts).\n")
        f.write(array("kWebMcpScript",
                      "(() => {\nconst module = {};\n%s\n;\nreturn module.exports.WebMCPScript();\n})()" % webmcp))
        f.write("\n// Playwright's coverage script: an expression whose value is its module's\n"
                "// exports, CoverageScript() and takeCoverageStashes() (coverageRecorder.ts).\n")
        f.write(array("kCoverageScript",
                      "(() => {\nconst module = {};\n%s\n;\nreturn module.exports;\n})()" % coverage))
        f.write("\n// Playwright's virtual WebAuthn authenticator, installed in a document\n"
                "// (server/credentials.ts).\n")
        f.write(array("kWebAuthnScript",
                      "(() => {\nconst module = {};\n%s\n;\nmodule.exports.inject()(globalThis);\n})();\n" % webauthn))
        f.write("\n}  // namespace zebkit\n\n#endif  // ZEBKIT_ENGINE_AUTOMATION_SCRIPTS_H_\n")


if __name__ == "__main__":
    main()
