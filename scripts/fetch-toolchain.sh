#!/usr/bin/env bash
# Download the pinned toolchain (toolchain.lock) into out/toolchain/ and
# generate the compiler wrappers the build scripts use:
#
#   out/toolchain/bin/zebkit-cc, zebkit-c++, zebkit-ar, zebkit-ranlib
#
# Build systems want a compiler to be one executable; the wrappers are that,
# and they pin the target so nothing can accidentally build for the host.

source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

tarball="$CACHE_DIR/toolchain/$(basename "$TOOLCHAIN_URL")"
stamp="$TOOLCHAIN_DIR/.zebkit-stamp"
want="$TOOLCHAIN_SHA256 $TOOLCHAIN_TARGET $(sha256sum "${BASH_SOURCE[0]}" | cut -d' ' -f1)"

if [[ -f "$stamp" && "$(cat "$stamp")" == "$want" ]]; then
    log "toolchain is up to date: $TOOLCHAIN_DIR"
    exit 0
fi

mkdir -p "$(dirname "$tarball")" "$TOOLCHAIN_DIR/bin"
if [[ ! -f "$tarball" ]] || ! echo "$TOOLCHAIN_SHA256  $tarball" | sha256sum -c --status; then
    log "downloading $TOOLCHAIN_URL"
    curl -fL --retry 3 -o "$tarball.part" "$TOOLCHAIN_URL"
    mv "$tarball.part" "$tarball"
fi
echo "$TOOLCHAIN_SHA256  $tarball" | sha256sum -c --status || die "checksum mismatch for $tarball"

log "extracting toolchain"
tar -xf "$tarball" -C "$TOOLCHAIN_DIR"
zig="$(find "$TOOLCHAIN_DIR" -maxdepth 2 -name zig -type f | head -1)"
[[ -x "$zig" ]] || die "no zig executable in $TOOLCHAIN_DIR"

# Headers and libraries of host packages (Wayland, libdrm, ...) live in the
# host's default search paths, which a cross compiler does not look in.
# -idirafter puts them behind the toolchain's own C library headers, so the
# host's newer glibc headers can never be picked up by accident.
multiarch="$(gcc -print-multiarch 2>/dev/null || echo x86_64-linux-gnu)"
# zig cc turns the undefined-behaviour sanitizer on for files compiled without
# optimization, which then need a runtime nobody links; switch it off.
compile_flags="-idirafter /usr/include/$multiarch -idirafter /usr/include -fno-sanitize=undefined"

wrapper() {
    local name="$1" body="$2"
    printf '#!/bin/sh\n# Generated by scripts/fetch-toolchain.sh.\n%s\n' "$body" > "$TOOLCHAIN_DIR/bin/$name"
    chmod +x "$TOOLCHAIN_DIR/bin/$name"
}
wrapper zebkit-cc      "exec \"$zig\" cc -target $TOOLCHAIN_TARGET $compile_flags \"\$@\""
wrapper zebkit-c++     "exec \"$zig\" c++ -target $TOOLCHAIN_TARGET $compile_flags \"\$@\""
wrapper zebkit-ar      "exec \"$zig\" ar \"\$@\""
wrapper zebkit-ranlib  "exec \"$zig\" ranlib \"\$@\""

echo "$want" > "$stamp"
log "toolchain ready: $("$TOOLCHAIN_DIR/bin/zebkit-cc" --version | head -1), target $TOOLCHAIN_TARGET"
