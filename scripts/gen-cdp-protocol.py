#!/usr/bin/env python3
"""Generate src/cdp/CDPProtocol.inc from the standard protocol definition.

    gen-cdp-protocol.py            write the file
    gen-cdp-protocol.py --check    fail if the file on disk is out of date

The endpoint checks the parameters of every command it implements against
the definition Chrome publishes (third_party/devtools-protocol), the way
Chrome does before a command reaches its handler. This writes the table it
checks against: one line per implemented command, with the name, the kind
and the optionality of each parameter.

Which commands are implemented is read from the sources: every string
literal in src/cdp that is the name of a standard command.
"""

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFINITION = ROOT / "third_party" / "devtools-protocol"
SOURCES = ROOT / "src" / "cdp"
OUTPUT = SOURCES / "CDPProtocol.inc"

KINDS = {"string": "s", "binary": "s", "integer": "i", "number": "n", "boolean": "b", "array": "a", "object": "o", "any": "*"}


def load():
    types, commands = {}, {}
    for name in ("browser_protocol.json", "js_protocol.json"):
        for domain in json.loads((DEFINITION / name).read_text())["domains"]:
            prefix = domain["domain"]
            for item in domain.get("types", []):
                types[f"{prefix}.{item['id']}"] = item
            for item in domain.get("commands", []):
                commands[f"{prefix}.{item['name']}"] = (prefix, item)
    return types, commands


def kind(types, domain, spec):
    while "$ref" in spec:
        name = spec["$ref"] if "." in spec["$ref"] else f"{domain}.{spec['$ref']}"
        domain, spec = name.split(".")[0], types[name]
    return KINDS[spec["type"]]


def generate():
    types, commands = load()
    literals = set()
    for source in sorted(SOURCES.glob("*.cpp")):
        literals.update(re.findall(r'"([A-Z][A-Za-z]+\.[a-zA-Z]+)"_s', source.read_text()))
    revision = (DEFINITION / "REVISION").read_text().split()[0]
    lines = [
        f"// Generated by scripts/gen-cdp-protocol.py from third_party/devtools-protocol ({revision}).",
        "// Do not edit. Each parameter is name, ':' (mandatory) or '?' (optional), and a kind:",
        "// s string, i integer, n number, b boolean, a array, o object, * anything.",
    ]
    for method in sorted(literals & commands.keys()):
        domain, item = commands[method]
        parameters = " ".join(
            f"{p['name']}{'?' if p.get('optional') else ':'}{kind(types, domain, p)}" for p in item.get("parameters", []))
        lines.append(f'{{ "{method}"_s, "{parameters}"_s }},')
    return "\n".join(lines) + "\n"


def main():
    text = generate()
    if "--check" in sys.argv[1:]:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date; run scripts/gen-cdp-protocol.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT.relative_to(ROOT)}: {text.count(chr(10)) - 3} commands")
    return 0


if __name__ == "__main__":
    sys.exit(main())
